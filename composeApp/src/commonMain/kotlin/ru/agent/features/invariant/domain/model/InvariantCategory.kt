package ru.agent.features.invariant.domain.model

/**
 * Категория инварианта.
 *
 * Определяет тип ограничений и правил.
 */
enum class InvariantCategory {
    /**
     * Архитектурные ограничения (паттерны, принципы).
     */
    ARCHITECTURE,

    /**
     * Технологические ограничения (инструменты, фреймворки).
     */
    TECHNOLOGY,

    /**
     * Стек технологий (версии, библиотеки).
     */
    STACK,

    /**
     * Бизнес-правила (процессы, требования).
     */
    BUSINESS_RULE
}

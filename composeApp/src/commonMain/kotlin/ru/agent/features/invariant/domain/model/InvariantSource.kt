package ru.agent.features.invariant.domain.model

/**
 * Источник инварианта.
 *
 * Определяет кто создал инвариант.
 */
enum class InvariantSource {
    /**
     * Системный инвариант - создан автоматически.
     * System CRITICAL инварианты защищены от удаления.
     */
    SYSTEM,

    /**
     * Пользовательский инвариант - создан пользователем.
     * Можно удалять и изменять.
     */
    USER
}

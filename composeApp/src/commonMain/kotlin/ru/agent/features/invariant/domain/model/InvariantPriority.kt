package ru.agent.features.invariant.domain.model

/**
 * Приоритет инварианта.
 *
 * Определяет критичность правила.
 */
enum class InvariantPriority {
    /**
     * Критический приоритет - нарушение недопустимо.
     * System инварианты с этим приоритетом нельзя удалить.
     */
    CRITICAL,

    /**
     * Высокий приоритет - нарушение крайне нежелательно.
     */
    HIGH,

    /**
     * Средний приоритет - нарушение нежелательно, но допустимо.
     */
    MEDIUM
}
